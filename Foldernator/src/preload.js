  statusBoard: inv('status:board'),
  driveCheck: inv('drive:check'),
  driveChildColors: inv('drive:childColors'),
  driveDeep: inv('drive:deep'),
  onDriveItem: on('drive:item'),
  onDriveProgress: on('drive:progress'),
  onDriveDone: on('drive:done'),
