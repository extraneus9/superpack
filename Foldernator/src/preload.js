  newFile: inv('fs:newFile'),
  rename: inv('fs:rename'),
  fileOp: inv('fs:op'),

  searchStart: inv('search:start'),
  searchCancel: inv('search:cancel'),
  quickAccess: inv('quickaccess:get'),
  galleryStart: inv('gallery:start'),

  open: inv('shell:open'),
  openWith: inv('shell:openWith'),
